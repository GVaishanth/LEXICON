export function filterLore(query='',category='All'){
  const q=query.trim().toLocaleLowerCase('en');
  return LORE_ENTRIES.filter(item=>
    (category==='All' || item.category===category) &&
    (!q || [item.word,item.origin,item.root,item.story,item.detail].some(text=>text.toLocaleLowerCase('en').includes(q)))
  );
}
